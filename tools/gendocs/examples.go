// Examples is the table in examples/README.md: every program in examples/
// that an entry links, with the entry, its domain and level.
func Examples() string {
	type row struct{ dir, title, entries, topic, level string }
	byDir := map[string]*row{}
	topic := map[string]string{}
	for _, c := range core.Categories {
		topic[c.ID] = c.Topic
	}
	for _, e := range core.Entries() {
		for _, u := range e.RealWorld {
			if u.Example == "" {
				continue
			}
			dir := strings.TrimPrefix(u.Example, "examples/")
			r, ok := byDir[dir]
			if !ok {
				r = &row{dir: dir, title: u.Title, topic: topic[e.Category], level: e.Level}
				byDir[dir] = r
			}
			if r.entries != "" {
				r.entries += ", "
			}
			r.entries += "`" + e.ID + "`"
		}
	}
	var rows []*row
	for _, r := range byDir {
		rows = append(rows, r)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].dir < rows[j].dir })
	var b strings.Builder
	b.WriteString("| Program | Scenario | Entries | Domain | Level |\n|---------|----------|---------|--------|-------|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| [`%s`](%s) | %s | %s | %s | %s |\n", r.dir, r.dir, cell(r.title), r.entries, r.topic, r.level)
	}
	return b.String()
}

// usedIn is the "Used in" note after an entry's summary in the catalog,
// linking its example programs relative to prefix.
func usedIn(e core.Entry, prefix string) string {
	if len(e.RealWorld) == 0 {
		return ""
	}
	var parts []string
	for _, u := range e.RealWorld {
		p := cell(u.Title)
		if u.Example != "" {
			p += fmt.Sprintf(" ([`%s`](%s%s))", strings.TrimPrefix(u.Example, "examples/"), prefix, u.Example)
		}
		parts = append(parts, p)
	}
	return " *Used in:* " + strings.Join(parts, "; ") + "."
}

// spliceBetween replaces the text between the markers b and e in doc.
func spliceBetween(doc, b, e, block string) string {
	i, j := strings.Index(doc, b), strings.Index(doc, e)
	if i < 0 || j < i {
		return doc
	}
	return doc[:i+len(b)] + "\n" + block + doc[j:]
}
