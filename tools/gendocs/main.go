// Command gendocs writes the parts of the documentation that are lists of
// entries, from the registry, so they cannot drift from the code: the catalog
// section of README.md (between the "catalog" markers) and
// docs/catalog.md, every entry with its cost and how to run it, and
// docs/learn.md, every learning path.
//
//	go run ./tools/gendocs          write them
//	go run ./tools/gendocs -check   fail if they are out of date (CI)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/braswelljr/alGOrithm/internal/core"
)

const (
	begin = "<!-- catalog:begin (generated by `go run ./tools/gendocs`; do not edit) -->"
	end   = "<!-- catalog:end -->"
)

func main() {
	check := flag.Bool("check", false, "report out-of-date files instead of writing them")
	flag.Parse()
	stale := false
	for path, want := range files() {
		got, _ := os.ReadFile(path)
		if bytes.Equal(got, want) {
			continue
		}
		if *check {
			fmt.Fprintf(os.Stderr, "gendocs: %s is out of date; run `go run ./tools/gendocs`\n", path)
			stale = true
			continue
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gendocs:", err)
			os.Exit(1)
		}
		fmt.Println("wrote", path)
	}
	if stale {
		os.Exit(1)
	}
}

// files returns every generated file's wanted contents.
func files() map[string][]byte {
	readme, err := os.ReadFile("README.md")
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendocs: run it from the repository root:", err)
		os.Exit(1)
	}
	out := map[string][]byte{
		"README.md":           []byte(Splice(string(readme), Summary())),
		"docs/catalog.md":     []byte(Catalog()),
		"docs/learn.md":       []byte(Learn()),
		"docs/cheatsheets.md": []byte(Cheatsheets()),
	}
	if ex, err := os.ReadFile("examples/README.md"); err == nil {
		out["examples/README.md"] = []byte(spliceBetween(string(ex), examplesBegin, examplesEnd, Examples()))
	}
	return out
}

// Splice replaces the text between the markers in doc with block.
func Splice(doc, block string) string {
	i, j := strings.Index(doc, begin), strings.Index(doc, end)
	if i < 0 || j < i {
		return doc
	}
	return doc[:i+len(begin)] + "\n" + block + doc[j:]
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// Summary is the README's catalog: each topic and category with its entries'
// names, linking to the full catalog.
func Summary() string {
	var b strings.Builder
	n := len(core.Entries())
	fmt.Fprintf(&b, "%d entries in %d categories. The full catalog, with every cost and the command to run each, is [docs/catalog.md](docs/catalog.md).\n", n, len(core.Categories))
	fmt.Fprintf(&b, "\nNew here? Walk one of the %d [learning paths](docs/learn.md), or run `algorithm learn`.\n", len(core.Paths()))
	topic := ""
	for _, c := range core.Categories {
		if c.Topic != topic {
			topic = c.Topic
			fmt.Fprintf(&b, "\n### %s\n\n| Category | Entries |\n|----------|---------|\n", topic)
		}
		var names []string
		for _, e := range core.InCategory(c.ID) {
			names = append(names, e.Name)
		}
		fmt.Fprintf(&b, "| [%s](%s) | %s |\n", c.Name, dir(c), cell(strings.Join(names, ", ")))
	}
	b.WriteString("\n")
	return b.String()
}

// Catalog is docs/catalog.md: every entry, by topic and category.
func Catalog() string {
	var b strings.Builder
	b.WriteString("# Catalog\n\nEvery algorithm, data structure and simulation in alGOrithm, generated from the registry (`go run ./tools/gendocs`), by topic and category. Each entry gives its cost, the Go function that implements it, and the command that runs its example; `algorithm info ID` says more, `algorithm source ID` prints the code, and the visualizer animates the ones marked animated.\n")
	topic := ""
	for _, c := range core.Categories {
		if c.Topic != topic {
			topic = c.Topic
			fmt.Fprintf(&b, "\n## %s\n", topic)
		}
		fmt.Fprintf(&b, "\n### %s\n\n%s Package [`%s`](../%s).\n\n", c.Name, c.Summary, c.ID, dir(c))
		b.WriteString("| Entry | Level | Time | Space | Tags | Go | Try it |\n|-------|-------|------|-------|------|----|--------|\n")
		for _, e := range core.InCategory(c.ID) {
			fmt.Fprintf(&b, "| **%s**: %s%s | %s | %s | %s | %s | [`%s.%s`](../pkg/%s) | `algorithm run %s --example` |\n",
				cell(e.Name), cell(e.Summary), usedIn(e, "../"), e.Level, cell(e.Time), cell(e.Space), strings.Join(e.Tags, ", "), e.Package, e.Func, e.File, e.ID)
		}
	}
	b.WriteString(tagIndex())
	return b.String()
}

// tagIndex lists every tag with its meaning and the entries carrying it.
func tagIndex() string {
	var b strings.Builder
	b.WriteString("\n## By tag\n\n| Tag | Meaning | Entries |\n|-----|---------|---------|\n")
	tags := make([]string, 0, len(core.Vocabulary))
	for t := range core.Vocabulary {
		tags = append(tags, t)
	}
	sort.Strings(tags)
	for _, t := range tags {
		var ids []string
		for _, e := range core.WithTag(t) {
			ids = append(ids, "`"+e.ID+"`")
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", t, cell(core.Vocabulary[t]), strings.Join(ids, ", "))
	}
	return b.String()
}

// dir is a category's package directory in the repository ("pkg/algorithms/sorting").
func dir(c core.Category) string { return strings.TrimPrefix(c.Import, core.Module+"/") }
