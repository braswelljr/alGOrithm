import {
  accents,
  accentTokens,
  css,
  defaultAccent,
  defaultNeutral,
  defaultViz,
  neutrals,
  status,
  surfaces,
  vizPalettes,
  vizRoles,
  type Mode
} from '../src/lib/colors.ts';

const block = (selector: string, vars: Record<string, string>, extra = '') =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')}${extra}\n}\n`;

const neutralVars = (id: string, mode: Mode) => {
  const n = neutrals.find((x) => x.id === id)!;
  return Object.fromEntries(Object.entries(surfaces(n, mode)).map(([k, v]) => [k, css(v)]));
};
const accentVars = (id: string, mode: Mode) => {
  const a = accents.find((x) => x.id === id)!;
  const n = neutrals.find((x) => x.id === defaultNeutral)!;
  return Object.fromEntries(Object.entries(accentTokens(a, mode, n)).map(([k, v]) => [k, css(v)]));
};
const statusVars = (mode: Mode) =>
  Object.fromEntries(Object.entries(status[mode]).map(([k, v]) => [k, css(v)]));
const vizVars = (id: string, mode: Mode) => {
  const p = vizPalettes.find((x) => x.id === id)!;
  return Object.fromEntries(vizRoles.map((r) => [`viz-${r}`, css(p.colors[mode][r])]));
};

/** The whole stylesheet, as a string (the test compares it with the file). */
export function renderColorsCss(): string {
  const parts: string[] = [
    '/* Generated by scripts/colors.ts from src/lib/colors.ts; do not edit.\n' +
      '   Select a theme with data-neutral, data-accent and data-viz on <html>,\n' +
      '   and dark mode with the .dark class (system preference before it is set). */\n'
  ];
  const all = (mode: Mode) => ({
    ...neutralVars(defaultNeutral, mode),
    ...accentVars(defaultAccent, mode),
    ...statusVars(mode),
    ...vizVars(defaultViz, mode)
  });
  parts.push(block(':root', all('light'), '\n  color-scheme: light;'));
  parts.push(block(':root.dark', all('dark'), '\n  color-scheme: dark;'));
  // A region drawn in one mode whatever the page's (the /ui gallery's columns).
  parts.push(block('.scope-light', all('light'), '\n  color-scheme: light;'));
  parts.push(block('.scope-dark', all('dark'), '\n  color-scheme: dark;'));
  const variants: [string, string, (id: string, m: Mode) => Record<string, string>][] = [
    ...neutrals
      .filter((n) => n.id !== defaultNeutral)
      .map((n) => ['neutral', n.id, neutralVars] as [string, string, typeof neutralVars]),
    ...accents
      .filter((a) => a.id !== defaultAccent)
      .map((a) => ['accent', a.id, accentVars] as [string, string, typeof accentVars]),
    ...vizPalettes
      .filter((p) => p.id !== defaultViz)
      .map((p) => ['viz', p.id, vizVars] as [string, string, typeof vizVars])
  ];
  for (const [attr, id, vars] of variants) {
    parts.push(block(`:root[data-${attr}='${id}']`, vars(id, 'light')));
    parts.push(block(`:root.dark[data-${attr}='${id}']`, vars(id, 'dark')));
  }
  // Before next-themes sets a class (or with scripts off), follow the system.
  const fallback: string[] = [
    block(':root:not(.light):not(.dark)', all('dark'), '\n  color-scheme: dark;')
  ];
  for (const [attr, id, vars] of variants) {
    fallback.push(block(`:root:not(.light):not(.dark)[data-${attr}='${id}']`, vars(id, 'dark')));
  }
  parts.push(
    `@media (prefers-color-scheme: dark) {\n${fallback
      .join('')
      .split('\n')
      .map((l) => (l ? `  ${l}` : l))
      .join('\n')}}\n`
  );
  // Asked for more contrast and no palette chosen: the high-contrast one.
  const hc = (mode: Mode) => vizVars('contrast', mode);
  parts.push(
    `@media (prefers-contrast: more) {\n${[
      block(':root:not([data-viz])', { ...hc('light'), border: 'var(--control)' }),
      block(':root.dark:not([data-viz])', { ...hc('dark'), border: 'var(--control)' })
    ]
      .join('')
      .split('\n')
      .map((l) => (l ? `  ${l}` : l))
      .join('\n')}}\n`
  );
  return parts.join('\n');
}
