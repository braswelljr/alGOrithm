// classify gives e its kind, level and tags: the category's, the curated
// ones, and those that follow from how it runs.
func classify(e *Entry) {
	d, ok := categoryDefaults[e.Category]
	if !ok {
		d.kind, d.level = KindAlgorithm, Intermediate
	}
	e.Kind, e.Level = d.kind, d.level
	if e.Input == Ops && e.Kind == KindAlgorithm {
		e.Kind = KindDataStructure
	}
	if l, ok := entryLevels[e.ID]; ok {
		e.Level = l
	}
	tags := append(append([]string(nil), d.tags...), entryTags[e.ID]...)
	if e.Traced || len(e.Ops) > 0 {
		tags = append(tags, "animated")
	}
	if e.Input == Ops {
		tags = append(tags, "interactive")
	}
	slices.Sort(tags)
	e.Tags = slices.Compact(tags)
}

// WithTag returns the entries carrying tag (case ignored).
func WithTag(tag string) []Entry {
	tag = strings.ToLower(strings.TrimSpace(tag))
	var out []Entry
	for _, e := range Entries() {
		if slices.Contains(e.Tags, tag) {
			out = append(out, e)
		}
	}
	return out
}
